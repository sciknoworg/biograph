"""Drives scripts/build_site.py as a subprocess and reads back what it wrote.

This module is the only place in experiments/ that knows the CLI. Everything about how
the pipeline is invoked is decided here, once:

  --text <path>          the documented text entry point; no PDF parsing in the loop
  --domain benchmark_*   output lands in subjects/benchmark_<adapter>/, never beside a
                         real person (and the sandbox is thrown away anyway)
  --keep-rejected        REQUIRED. Without it, a document the scope gate refuses has
                         its source file deleted by extract(): os.remove(pdf_path).
                         Benchmark inputs are generated, so losing one is recoverable,
                         but a harness that silently eats its own corpus on rejection is
                         not a harness. This flag is not optional and not configurable.
  --scope-out <path>     the scope verdict for every document, written on rejection too.
                         Scope-gate attrition is a reported column in every results
                         table, because SCOPE_DEFINITION is in the prompt whether or not
                         --strict-scope is passed and three of the five benchmarks are
                         nowhere near the biographical-essay genre it describes.
  (never --strict-scope) the four extra rules -- English, one central figure,
                         substantial, in-domain -- would reject short benchmark
                         documents on length alone.

Two behaviours of the CLI the caller must not be surprised by:

1. `main()` runs build() after extract(), and build() calls validate_subject(), which
   exits non-zero on a schema or referential-integrity failure. The JSON is already on
   disk at that point. So a non-zero exit means "the draft did not validate", NOT "no
   output" -- we read the document folder either way and record `exit_code`. For a
   benchmark that distinction matters: an extraction that validates and one that does
   not are different results, and conflating them with "failed" loses the finding.

2. Extraction is sampled at temperature 0.2, so it is not deterministic. Runs are
   cached by (text, model, base_url) and repeated k times for variance, rather than
   pretending a single run is the system's score.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import time
from dataclasses import dataclass

from .interface import BenchmarkDoc, Extraction, GroundingReport
from .sandbox import DOMAIN_PREFIX, Sandbox

DATA_FILES = ("entities", "events", "relations", "sources")


@dataclass
class ModelConfig:
    """Credentials and model, from the environment. Never from the command line: a key
    on argv lands in shell history and in every log line that echoes the command."""

    model: str
    base_url: str
    api_key: str

    @classmethod
    def from_env(cls) -> "ModelConfig":
        missing = [v for v in ("BIOGRAPH_MODEL", "BIOGRAPH_BASE_URL", "BIOGRAPH_API_KEY")
                   if not os.environ.get(v)]
        if missing:
            raise SystemExit("set " + ", ".join(missing) + " before running the harness "
                             "(see PIPELINE_GUIDE.md)")
        return cls(model=os.environ["BIOGRAPH_MODEL"],
                   base_url=os.environ["BIOGRAPH_BASE_URL"],
                   api_key=os.environ["BIOGRAPH_API_KEY"])

    def fingerprint(self) -> str:
        return f"{self.base_url}::{self.model}"


def python_exe() -> str:
    """The interpreter running the harness. `python3` is not on PATH on Windows, where
    this repository is developed; sys.executable always is."""
    return sys.executable


def cache_key(doc: BenchmarkDoc, cfg: ModelConfig, core_hash: str, repeat: int,
              condition: str = "gate_on") -> str:
    """`condition` is part of the key because the gate-on and gate-off runs of the same
    document under the same core hash are different experiments with the same inputs.
    Omitting it would let an ablation run silently serve the baseline's cached result."""
    h = hashlib.sha256()
    for part in (doc.text, cfg.fingerprint(), core_hash, str(repeat), condition):
        h.update(part.encode("utf-8"))
        h.update(b"\x00")
    return h.hexdigest()[:24]


def _slug_ok(slug: str) -> bool:
    return bool(re.match(r"^[a-z][a-z0-9_]*$", slug))


def _find_doc_dir(sb: Sandbox, slug: str) -> str | None:
    """Where extract() put this document: subjects/<domain>/<slug>/<citation key>/.
    The citation key is generated by the model, so it is discovered, not predicted."""
    for dirpath, dirnames, filenames in os.walk(sb.subjects_dir):
        if os.path.basename(os.path.dirname(dirpath)) == slug and "events.json" in filenames:
            return dirpath
    return None


def _read_json(path: str, default):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return default


_GROUNDING_RE = re.compile(
    r"(\d+)\s*/\s*(\d+)\s+quotes\s+verbatim,\s*(\d+)\s*/\s*(\d+)\s+entity names present")


def parse_grounding(stdout: str) -> GroundingReport | None:
    """Read the numbers --check-grounding prints. The check itself is never
    reimplemented here -- reusing it is the whole point of benchmark 5."""
    m = _GROUNDING_RE.search(stdout)
    if not m:
        return None
    qv, qc, ep, ec = (int(g) for g in m.groups())
    issues = tuple(ln.rstrip() for ln in stdout.splitlines() if ln.startswith("    "))
    return GroundingReport(quotes_checked=qc, quotes_verbatim=qv,
                           entities_checked=ec, entities_present=ep, issues=issues)


class Runner:
    def __init__(self, sandbox: Sandbox, cfg: ModelConfig, adapter_name: str,
                 cache_dir: str | None = None, timeout: int = 1800, verbose: bool = True,
                 ignore_scope: bool = False):
        self.sb = sandbox
        self.cfg = cfg
        self.domain = f"{DOMAIN_PREFIX}_{adapter_name}"
        self.cache_dir = cache_dir
        self.timeout = timeout
        self.verbose = verbose
        #: The ablation condition. The scope verdict is still produced and still recorded --
        #: only its power to stop the run is removed -- so a gate-off run yields paired data:
        #: what the gate WOULD have said, and what the extractor produced anyway. Reported as
        #: a distinct condition, never merged with gate-on results.
        self.ignore_scope = ignore_scope
        if cache_dir:
            os.makedirs(cache_dir, exist_ok=True)

    # ------------------------------------------------------------------ run

    def extract(self, doc: BenchmarkDoc, repeat: int = 0) -> Extraction:
        if not _slug_ok(doc.slug):
            raise ValueError(f"slug {doc.slug!r} will be rejected by build_site.py "
                             f"(needs ^[a-z][a-z0-9_]*$)")
        key = cache_key(doc, self.cfg, self.sb.hashes["scripts/build_site.py"], repeat,
                        condition="gate_off" if self.ignore_scope else "gate_on")
        cached = self._load_cached(doc, key)
        if cached is not None:
            return cached

        text_path = os.path.join(self.sb.root, "data", f"_in_{doc.slug}.txt")
        os.makedirs(os.path.dirname(text_path), exist_ok=True)
        with open(text_path, "w", encoding="utf-8") as f:
            f.write(doc.text)
        # Removed first: --scope-out is only written when the model answers, so a file
        # left by an earlier repeat of the same slug would otherwise be read back as
        # this run's verdict if the call failed.
        scope_path = os.path.join(self.sb.root, f"_scope_{doc.slug}.json")
        if os.path.isfile(scope_path):
            os.remove(scope_path)

        cmd = [python_exe(), self.sb.build_site, doc.slug,
               "--text", text_path,
               "--name", doc.name,
               "--domain", self.domain,
               "--keep-rejected",                 # see module docstring: not optional
               "--scope-out", scope_path,
               "--model", self.cfg.model,
               "--base-url", self.cfg.base_url]
        if self.ignore_scope:
            cmd.append("--ignore-scope")
        env = dict(os.environ, BIOGRAPH_API_KEY=self.cfg.api_key)

        start = time.perf_counter()
        proc = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8",
                              errors="replace", env=env, timeout=self.timeout,
                              cwd=self.sb.root)
        wall = time.perf_counter() - start

        scope = _read_json(scope_path, None)
        doc_dir = _find_doc_dir(self.sb, doc.slug)
        payload = {k: () for k in DATA_FILES}
        subject = None
        if doc_dir:
            payload = {k: tuple(_read_json(os.path.join(doc_dir, f"{k}.json"), []))
                       for k in DATA_FILES}
            subject = _read_json(os.path.join(os.path.dirname(doc_dir), "subject.json"), None)

        ex = Extraction(doc_id=doc.doc_id, slug=doc.slug, subject=subject,
                        entities=payload["entities"], events=payload["events"],
                        relations=payload["relations"], sources=payload["sources"],
                        scope=scope, exit_code=proc.returncode, wall_seconds=wall,
                        stdout=proc.stdout, stderr=proc.stderr)
        if self.verbose:
            self._log(doc, ex)
        self._save_cached(key, ex)
        return ex

    def check_grounding(self, ex: Extraction) -> Extraction:
        """Second CLI call: --check-grounding on what was just written. Benchmark 5 is
        this number; benchmarks 1-4 report it alongside their own metric, because an
        extraction that scores well while citing quotes that are not in the source is
        not a result worth reporting."""
        if ex.empty:
            return ex
        cmd = [python_exe(), self.sb.build_site, ex.slug, "--check-grounding"]
        proc = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8",
                              errors="replace", timeout=300, cwd=self.sb.root)
        return Extraction(**{**ex.__dict__, "grounding": parse_grounding(proc.stdout)})

    def cleanup_subject(self, slug: str) -> None:
        """Remove one document's output from the sandbox between runs, so a repeat does
        not merge with its own previous attempt -- load_subject_documents() merges every
        document folder under a subject, which for a k-repeat run would silently union
        k extractions into one graph."""
        for dirpath, dirnames, _ in os.walk(self.sb.subjects_dir):
            if slug in dirnames and os.path.isdir(os.path.join(dirpath, slug)):
                shutil.rmtree(os.path.join(dirpath, slug), ignore_errors=True)
                return

    # ------------------------------------------------------------------ cache

    def _cache_path(self, key: str) -> str | None:
        return os.path.join(self.cache_dir, f"{key}.json") if self.cache_dir else None

    def _load_cached(self, doc: BenchmarkDoc, key: str) -> Extraction | None:
        path = self._cache_path(key)
        if not path or not os.path.isfile(path):
            return None
        raw = _read_json(path, None)
        if not raw:
            return None
        g = raw.pop("grounding", None)
        raw.pop("doc_id", None)
        ex = Extraction(doc_id=doc.doc_id, **{k: (tuple(v) if isinstance(v, list) else v)
                                              for k, v in raw.items()})
        if g:
            ex = Extraction(**{**ex.__dict__, "grounding": GroundingReport(
                **{**g, "issues": tuple(g.get("issues", ()))})})
        if self.verbose:
            print(f"  [cache] {doc.doc_id}")
        return ex

    def _save_cached(self, key: str, ex: Extraction) -> None:
        path = self._cache_path(key)
        if not path:
            return
        d = dict(ex.__dict__)
        d["grounding"] = ex.grounding.__dict__ if ex.grounding else None
        for k in DATA_FILES:
            d[k] = list(d[k])
        with open(path, "w", encoding="utf-8") as f:
            json.dump(d, f, ensure_ascii=False)

    # ------------------------------------------------------------------ log

    def _log(self, doc: BenchmarkDoc, ex: Extraction) -> None:
        if not ex.in_scope and ex.empty:
            reason = (ex.scope or {}).get("reason", "")
            print(f"  [out of scope] {doc.doc_id}: {reason[:90]}")
        elif not ex.in_scope:
            # Gate off: the verdict was "unfit" and the extractor ran anyway. Reporting this
            # as "out of scope" would hide the very result the ablation exists to produce.
            flag = "" if ex.exit_code == 0 else f" [did not validate: exit {ex.exit_code}]"
            print(f"  [unfit, extracted anyway] {doc.doc_id}: {len(ex.events)} events, "
                  f"{len(ex.relations)} relations ({ex.wall_seconds:.0f}s){flag}")
        elif ex.empty:
            print(f"  [empty] {doc.doc_id}: exit {ex.exit_code} ({ex.wall_seconds:.0f}s)")
        else:
            flag = "" if ex.exit_code == 0 else f" [did not validate: exit {ex.exit_code}]"
            print(f"  [ok] {doc.doc_id}: {len(ex.events)} events, "
                  f"{len(ex.relations)} relations ({ex.wall_seconds:.0f}s){flag}")
